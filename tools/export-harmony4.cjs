const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const reference = process.argv.includes('--reference');
const destination = path.join(root, 'build', reference ? 'api9-reference' : 'harmony4');
const marker = path.join(destination, '.exported-harmony4');
const newline = String.fromCharCode(10);
if (fs.existsSync(destination) && !fs.existsSync(marker)) {
  throw new Error(`Refusing to overwrite an existing directory: ${destination}`);
}
fs.mkdirSync(destination, { recursive: true });
fs.writeFileSync(marker, 'Generated by tools/export-harmony4.cjs' + newline);

function writeJson(relativePath, value, preserveExisting = false) {
  const target = path.join(destination, relativePath);
  if (preserveExisting && fs.existsSync(target)) return;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, JSON.stringify(value, null, 2) + newline);
}

for (const relativePath of ['AppScope', 'entry/src/main', 'entry/libs']) {
  fs.cpSync(path.join(root, relativePath), path.join(destination, relativePath), { recursive: true });
}
const app = JSON.parse(fs.readFileSync(path.join(root, 'AppScope/app.json5'), 'utf8'));
delete app.app.buildVersion;
writeJson('AppScope/app.json5', app);
const moduleProfile = JSON.parse(fs.readFileSync(path.join(root, 'entry/src/main/module.json5'), 'utf8'));
moduleProfile.module.deviceTypes = ['default', 'tablet'];
moduleProfile.module.uiSyntax = 'ets';
moduleProfile.module.metadata = [{ name: 'ArkTSPartialUpdate', value: 'true' }];
for (const ability of moduleProfile.module.abilities) {
  ability.srcEntrance = ability.srcEntry;
  delete ability.srcEntry;
  ability.visible = ability.exported;
  delete ability.exported;
  for (const skill of ability.skills || []) {
    skill.actions = skill.actions.map(action => action === 'ohos.want.action.home' ? 'action.system.home' : action);
  }
}
writeJson('entry/src/main/module.json5', moduleProfile);
writeJson('build-profile.json5', {
  app: {
    signingConfigs: [], compileSdkVersion: 9, compatibleSdkVersion: 9,
    products: [{ name: 'default' }]
  },
  modules: [{ name: 'entry', srcPath: './entry', targets: [{ name: 'default', applyToProducts: ['default'] }] }]
}, true);
writeJson('entry/build-profile.json5', {
  apiType: 'stageMode', buildOption: {},
  targets: [{ name: 'default', runtimeOS: reference ? 'OpenHarmony' : 'HarmonyOS' }]
}, true);
writeJson('package.json', {
  name: 'hmos-ai-gamer-harmony4', version: '1.0.0', private: true,
  ohos: { org: 'demo', directoryLevel: 'project', buildTool: 'hvigor' },
  dependencies: { '@ohos/hvigor': '2.4.2', '@ohos/hvigor-ohos-plugin': '2.4.2' }
});
writeJson('entry/package.json', {
  name: 'entry', version: '1.0.0', private: true,
  ohos: { org: 'demo', directoryLevel: 'module', buildTool: 'hvigor' }
});
fs.writeFileSync(path.join(destination, 'hvigorfile.js'),
  "module.exports = require('@ohos/hvigor-ohos-plugin').appTasks;" + newline);
fs.writeFileSync(path.join(destination, 'entry/hvigorfile.js'),
  "module.exports = require('@ohos/hvigor-ohos-plugin').hapTasks;" + newline);
fs.writeFileSync(path.join(destination, '.npmrc'), '@ohos:registry=https://repo.harmonyos.com/npm/' + newline);
console.log(`Exported ${reference ? 'OpenHarmony API9 reference (not a phone deployment)' : 'HarmonyOS API9 project'}: ${destination}`);
console.log(reference ? 'Build with the OpenHarmony API9 SDK for reference validation only.' :
  'Open the exported directory in DevEco Studio 3.1.1, install the HarmonyOS API9 SDK, sync and configure your debug signature.');
